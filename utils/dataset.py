"""
Target-image dataset for L_attn / L_gen: a folder of images generated by the base
model for the concept, all paired with the same `instance_prompt`.
Adapted from EraseAnything.
"""
from pathlib import Path

import torch
from PIL import Image
from PIL.ImageOps import exif_transpose
from torch.utils.data import Dataset
from torchvision import transforms
from torchvision.transforms.functional import crop

from utils.find_token import get_word_index

IMAGE_EXTENSIONS = (".png", ".jpg", ".jpeg", ".webp", ".bmp")


class DICEDataset(Dataset):
    def __init__(
        self,
        instance_data_root: str,
        instance_prompt: str,
        key_word: str,
        tokenizer_t5,
        max_sequence_length: int = 256,
        size: int = 512,
    ):
        root = Path(instance_data_root)
        if not root.exists():
            raise ValueError(f"Instance images root doesn't exist: {instance_data_root}")

        resize = transforms.Resize(size, interpolation=transforms.InterpolationMode.BILINEAR)
        to_tensor = transforms.Compose([transforms.ToTensor(), transforms.Normalize([0.5], [0.5])])
        self.pixel_values = []
        for path in sorted(root.iterdir()):
            if path.suffix.lower() not in IMAGE_EXTENSIONS:
                continue
            image = resize(exif_transpose(Image.open(path)).convert("RGB"))
            image = crop(image, *transforms.RandomCrop.get_params(image, (size, size)))
            self.pixel_values.append(to_tensor(image))

        # T5 positions of `key_word` in `instance_prompt`; empty (L_attn = 0) if it doesn't occur.
        self.remove_indices = (
            get_word_index(instance_prompt, key_word, tokenizer_t5, max_length=max_sequence_length)
            if key_word in instance_prompt
            else []
        )

    def __len__(self):
        return len(self.pixel_values)

    def __getitem__(self, index):
        return self.pixel_values[index]


def collate_fn(examples):
    return torch.stack(examples).to(memory_format=torch.contiguous_format).float()
